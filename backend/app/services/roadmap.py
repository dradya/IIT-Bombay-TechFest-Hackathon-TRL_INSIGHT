"""Technology roadmap derived strictly from the real gap analysis.

No invented timelines, budgets or probabilities. Phases group the existing
recommendations by priority (now/next/later) and every item names the actual
milestone(s) it addresses plus the framework's own validation and
documentation requirements.
"""
from __future__ import annotations

from typing import Any

from app.config.framework import Framework


def _action(recommendation: dict[str, Any], framework: Framework) -> dict[str, Any]:
    addresses = list(recommendation.get("addresses") or [])
    milestone_id = addresses[0] if addresses else None
    milestone = framework.milestone(milestone_id) if milestone_id else {}
    label = (
        recommendation.get("address_labels") or [milestone.get("label", milestone_id or "")]
    )[0]
    success = [
        f"'{label}' is confirmed by a dated, signed source in a new assessment."
    ]
    for document in recommendation.get("documentation", []) or []:
        success.append(f"Supplied document: {document}")
    return {
        "id": str(recommendation.get("id", "")),
        "title": str(recommendation.get("title", "")),
        "description": (
            f"Addresses milestone '{label}'."
            if label
            else "Addresses a documented readiness gap."
        ),
        "milestone": milestone_id,
        "milestone_label": label or None,
        "status": (
            str((recommendation.get("address_statuses") or ["missing"])[0])
        ),
        "priority": str(recommendation.get("priority", "medium")),
        "actions": list(recommendation.get("actions", []) or []),
        "validation_experiments": list(
            recommendation.get("validation_experiments", []) or []
        ),
        "documentation": list(recommendation.get("documentation", []) or []),
        "success_criteria": success,
    }


def build_roadmap(
    gap_analysis: dict[str, Any],
    framework: Framework,
    current_trl: int,
) -> dict[str, Any]:
    signal = (
        "Now"
        if gap_analysis.get("next_trl") is not None
        else "Sustain"
    )
    recommendations = list(gap_analysis.get("recommendations") or [])

    buckets = {"now": [], "next": [], "later": []}
    for recommendation in recommendations:
        priority = str(recommendation.get("priority", "medium"))
        bucket = "now" if priority == "high" else "next" if priority == "medium" else "later"
        buckets[bucket].append(_action(recommendation, framework))

    phases: list[dict[str, Any]] = []
    next_trl = gap_analysis.get("next_trl")
    definitions = [
        ("now", "Immediate actions", signal, current_trl + 1 if next_trl else current_trl),
        (
            "next",
            "Subsequent actions",
            "After the immediate gaps are closed",
            current_trl + 2 if next_trl and current_trl + 2 <= 9 else None,
        ),
        (
            "later",
            "Longer-horizon actions",
            "Following the subsequent actions",
            current_trl + 3 if next_trl and current_trl + 3 <= 9 else None,
        ),
    ]
    for phase_id, title, horizon_summary, target in definitions:
        items = buckets[phase_id]
        if not items:
            continue
        phases.append(
            {
                "id": f"phase_{phase_id}",
                "title": title,
                "horizon": phase_id,
                "target_trl": min(9, target) if target else None,
                "summary": horizon_summary,
                "items": items,
            }
        )

    if not phases:
        note = (
            "No open recommendations were generated by the gap analysis. "
            "This means every milestone in the assessed chain is already "
            "confirmed by documented evidence, or the assessment found no "
            "actionable gap. It does not guarantee operational readiness."
        )
    else:
        note = (
            "Phases group the real gap-analysis recommendations by priority. "
            "No schedule, cost or completion date is implied; a milestone only "
            "advances when a new assessment confirms it from documentation."
        )

    target_trl = gap_analysis.get("next_trl")
    return {
        "current_trl": int(current_trl),
        "current_name": str(gap_analysis.get("current_name", "")),
        "target_trl": int(target_trl) if target_trl else None,
        "target_name": gap_analysis.get("next_name"),
        "phases": phases,
        "note": note,
    }
